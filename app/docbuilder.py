"""Step 5 of the workflow: turn the finished draft into a polished Word document (python-docx)."""
import re
from datetime import date
from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Inches, Pt, RGBColor

from app.schemas import AgentContext, Plan, Section

NAVY = RGBColor(0x1F, 0x3A, 0x5F)
GREY = RGBColor(0x59, 0x59, 0x59)
FONT = "Calibri"


# ---------- small helpers ----------
def _shade(cell, hex_fill: str) -> None:
    shading = OxmlElement("w:shd")
    shading.set(qn("w:val"), "clear")
    shading.set(qn("w:color"), "auto")
    shading.set(qn("w:fill"), hex_fill)
    cell._tc.get_or_add_tcPr().append(shading)


def _add_page_number(paragraph) -> None:
    """Insert a live PAGE field (Word has no simple API for this)."""
    run = paragraph.add_run()
    parts = [("fldChar", "begin"), ("instrText", " PAGE "), ("fldChar", "separate"), ("t", "1"), ("fldChar", "end")]
    for tag, value in parts:
        if tag == "fldChar":
            element = OxmlElement("w:fldChar")
            element.set(qn("w:fldCharType"), value)
        elif tag == "instrText":
            element = OxmlElement("w:instrText")
            element.set(qn("xml:space"), "preserve")
            element.text = value
        else:
            element = OxmlElement("w:t")
            element.text = value
        run._r.append(element)


def _style_font(style, size=None, bold=None, color=None) -> None:
    style.font.name = FONT
    style.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if size:
        style.font.size = Pt(size)
    if bold is not None:
        style.font.bold = bold
    if color is not None:
        style.font.color.rgb = color


# ---------- document parts ----------
def _setup_document(doc: Document, title: str) -> None:
    for section in doc.sections:
        section.left_margin = section.right_margin = Inches(1)
        section.top_margin = section.bottom_margin = Inches(0.9)

    normal = doc.styles["Normal"]
    _style_font(normal, size=11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.1
    _style_font(doc.styles["Title"], size=26, bold=True, color=NAVY)
    _style_font(doc.styles["Heading 1"], size=16, bold=True, color=NAVY)
    doc.styles["Heading 1"].paragraph_format.space_before = Pt(18)
    doc.styles["Heading 1"].paragraph_format.keep_with_next = True
    _style_font(doc.styles["List Bullet"], size=11)

    section = doc.sections[0]
    header = section.header.paragraphs[0]
    header.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = header.add_run(title)
    run.font.size, run.font.color.rgb = Pt(9), GREY

    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = footer.add_run("Generated by the Autonomous Document Agent   |   Page ")
    run.font.size, run.font.color.rgb = Pt(9), GREY
    _add_page_number(footer)
    for run in footer.runs:
        run.font.size = Pt(9)
        run.font.color.rgb = GREY

    doc.core_properties.title = title
    doc.core_properties.author = "Autonomous Document Agent"


def _add_title_block(doc: Document, plan: Plan) -> None:
    doc.add_heading(plan.title, level=0)
    label = plan.doc_type.replace("_", " ").title()
    subtitle = doc.add_paragraph()
    run = subtitle.add_run(f"{label}   |   Prepared for: {plan.audience}   |   {date.today():%d %B %Y}")
    run.font.size, run.font.color.rgb = Pt(10.5), GREY
    subtitle.paragraph_format.space_after = Pt(12)


def _add_table(doc: Document, columns, rows) -> None:
    table = doc.add_table(rows=1, cols=len(columns))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, text in zip(table.rows[0].cells, columns):
        cell.text = ""
        run = cell.paragraphs[0].add_run(text)
        run.bold, run.font.size, run.font.color.rgb = True, Pt(10), RGBColor(0xFF, 0xFF, 0xFF)
        _shade(cell, "1F3A5F")
    for index, row in enumerate(rows):
        cells = table.add_row().cells
        for cell, text in zip(cells, row):
            cell.text = ""
            run = cell.paragraphs[0].add_run(text)
            run.font.size = Pt(10)
            if index % 2 == 1:
                _shade(cell, "F2F5F9")
    doc.add_paragraph()  # breathing room after the table


def _add_section(doc: Document, number, section: Section) -> None:
    heading = f"{number}. {section.heading}" if number else section.heading
    doc.add_heading(heading, level=1)
    for text in section.paragraphs:
        doc.add_paragraph(text)
    if section.columns:
        _add_table(doc, section.columns, section.rows)
    for text in section.bullets:
        doc.add_paragraph(text, style="List Bullet")


def _add_assumptions_box(doc: Document, plan: Plan) -> None:
    if not (plan.assumptions or plan.conflicts):
        return
    doc.add_heading("Assumptions and Key Decisions", level=1)
    cell = doc.add_table(rows=1, cols=1).rows[0].cells[0]
    _shade(cell, "EAF1F8")
    first = True

    def label(text: str):
        nonlocal first
        paragraph = cell.paragraphs[0] if first else cell.add_paragraph()
        first = False
        run = paragraph.add_run(text)
        run.bold, run.font.color.rgb = True, NAVY

    if plan.assumptions:
        label("Assumptions made by the agent")
        for text in plan.assumptions:
            cell.add_paragraph(text, style="List Bullet")
    if plan.conflicts:
        label("Conflicting requirements and how they were resolved")
        for conflict in plan.conflicts:
            paragraph = cell.add_paragraph(style="List Bullet")
            paragraph.add_run(f"{conflict.issue}: ").bold = True
            paragraph.add_run(conflict.resolution)
    doc.add_paragraph()


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:50] or "document"


# ---------- public entry point ----------
def build_docx(ctx: AgentContext, out_dir: Path, request_id: str) -> Path:
    plan = ctx.plan
    doc = Document()
    _setup_document(doc, plan.title)
    _add_title_block(doc, plan)
    if ctx.summary:
        _add_section(doc, None, ctx.summary)
    _add_assumptions_box(doc, plan)
    for number, section in enumerate(ctx.sections, start=1):
        _add_section(doc, number, section)
    if ctx.data:
        note = doc.add_paragraph()
        run = note.add_run(
            "Note: figures in this document are illustrative estimates based on mock data "
            "and must be validated before approval."
        )
        run.italic, run.font.size, run.font.color.rgb = True, Pt(9), GREY

    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{_slug(plan.title)}-{request_id}.docx"
    doc.save(path)
    return path
